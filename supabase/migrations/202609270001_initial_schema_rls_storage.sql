create or replace function public.touch_updated_at() returns trigger language plpgsql as $$ begin new.updated_at=now(); return new; end $$;
do $$ declare t text; begin
  foreach t in array array['users','farmer_profiles','crops','diseases','pests','alerts','expert_reviews'] loop
    execute format('drop trigger if exists touch_updated_at on public.%I',t);
    execute format('create trigger touch_updated_at before update on public.%I for each row execute function public.touch_updated_at()',t);
  end loop;
end $$;
create or replace function public.current_app_role() returns text language sql stable security definer set search_path=public as $$ select role from public.users where auth_uid=auth.uid() limit 1 $$;
create or replace function public.current_app_user_id() returns bigint language sql stable security definer set search_path=public as $$ select id from public.users where auth_uid=auth.uid() limit 1 $$;
create or replace function public.expert_can_access_scan(p_scan_id bigint) returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.expert_reviews r
    where r.scan_id=p_scan_id and (r.status in ('pending','assigned') or (r.status='reviewed' and r.expert_id=public.current_app_user_id()))
      and (r.expert_id is null or r.expert_id=public.current_app_user_id()))
$$;
create or replace function public.expert_can_access_crop(p_crop_id bigint) returns boolean
language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.expert_reviews r join public.crop_scans s on s.id=r.scan_id
    where s.crop_id=p_crop_id and (r.status in ('pending','assigned') and (r.expert_id is null or r.expert_id=public.current_app_user_id())
      or r.status='reviewed' and r.expert_id=public.current_app_user_id()))
$$;
revoke all on function public.current_app_role() from public;
revoke all on function public.current_app_user_id() from public;
grant execute on function public.current_app_role() to authenticated;
grant execute on function public.current_app_user_id() to authenticated;
revoke all on function public.expert_can_access_scan(bigint) from public;
grant execute on function public.expert_can_access_scan(bigint) to authenticated;
revoke all on function public.expert_can_access_crop(bigint) from public;
grant execute on function public.expert_can_access_crop(bigint) to authenticated;

-- Link legacy SQLite account rows by verified Supabase email. Password hashes are intentionally not imported.
create or replace function public.claim_or_create_user() returns setof public.users
language plpgsql security definer set search_path=public,auth as $$
declare v_auth auth.users%rowtype; v_user public.users%rowtype; v_name text;
begin
  select * into v_auth from auth.users where id=auth.uid();
  if not found or v_auth.email_confirmed_at is null then raise exception 'verified auth session required'; end if;
  v_name := coalesce(v_auth.raw_user_meta_data->>'full_name','');
  update public.users set auth_uid=v_auth.id,email=lower(v_auth.email),updated_at=now()
    where lower(email)=lower(v_auth.email) and auth_uid is null returning * into v_user;
  if not found then
    insert into public.users(auth_uid,email,role) values(v_auth.id,lower(v_auth.email),'FARMER')
      on conflict(auth_uid) do update set email=excluded.email returning * into v_user;
  end if;
  insert into public.farmer_profiles(user_id,full_name) values(v_user.id,v_name)
    on conflict(user_id) do update set full_name=case when farmer_profiles.full_name='' then excluded.full_name else farmer_profiles.full_name end;
  return next v_user;
end $$;
revoke all on function public.claim_or_create_user() from public;
grant execute on function public.claim_or_create_user() to authenticated;
create or replace function public.handle_new_auth_user() returns trigger language plpgsql security definer set search_path=public,auth as $$
declare v_user public.users%rowtype;
begin
  update public.users set auth_uid=new.id,email=lower(new.email),updated_at=now()
    where lower(email)=lower(new.email) and auth_uid is null returning * into v_user;
  if not found then
    insert into public.users(auth_uid,email,role) values(new.id,lower(new.email),'FARMER')
      on conflict(auth_uid) do update set email=excluded.email returning * into v_user;
  end if;
  insert into public.farmer_profiles(user_id,full_name) values(v_user.id,coalesce(new.raw_user_meta_data->>'full_name','')) on conflict(user_id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_auth_user();

