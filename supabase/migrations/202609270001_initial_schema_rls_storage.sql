-- CropGuard production schema. Apply with `supabase db push` after linking a project.
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  auth_uid uuid unique references auth.users(id) on delete cascade,
  email text not null unique,
  password_hash text,
  role text not null default 'FARMER' check (role in ('FARMER','EXPERT','ADMIN')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.farmer_profiles (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references public.users(id) on delete cascade,
  full_name text not null default '', mobile text, state text, district text, village text,
  language text not null default 'English', farm_area numeric(12,3) check (farm_area is null or farm_area >= 0),
  soil_type text, irrigation_type text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.crops (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 80), variety text, sowing_date date, growth_stage text,
  location text, area numeric(12,3) check (area is null or area >= 0), soil_type text, irrigation_type text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.diseases (
  id bigint generated by default as identity primary key, name text not null unique, scientific_name text,
  crops jsonb not null default '[]', symptoms jsonb not null default '[]', causes jsonb not null default '[]',
  favorable_conditions jsonb not null default '[]', prevention jsonb not null default '[]',
  cultural_management jsonb not null default '[]', biological_management jsonb not null default '[]',
  chemical_management jsonb not null default '[]', severity_indicators jsonb not null default '[]',
  kind text not null default 'disease' check (kind='disease'), created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.pests (
  id bigint generated by default as identity primary key, name text not null unique, scientific_name text,
  crops jsonb not null default '[]', symptoms jsonb not null default '[]', causes jsonb not null default '[]',
  favorable_conditions jsonb not null default '[]', prevention jsonb not null default '[]',
  cultural_management jsonb not null default '[]', biological_management jsonb not null default '[]',
  chemical_management jsonb not null default '[]', severity_indicators jsonb not null default '[]',
  kind text not null default 'pest' check (kind='pest'), created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.crop_scans (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete set null, crop_id bigint references public.crops(id) on delete set null,
  filename text, kind text not null check (kind in ('disease','pest')), name text not null,
  confidence double precision check (confidence is null or confidence between 0 and 1), severity text,
  risk_level text check (risk_level is null or risk_level in ('LOW','MEDIUM','HIGH')),
  risk_score smallint check (risk_score is null or risk_score between 0 and 100),
  risk_reasons jsonb not null default '[]', weather jsonb not null default '{}', model_name text, model_version text,
  prediction_timestamp timestamptz, created_at timestamptz not null default now()
);
create table if not exists public.recommendations (
  id bigint generated by default as identity primary key,
  crop_scan_id bigint not null references public.crop_scans(id) on delete cascade,
  body text not null, created_at timestamptz not null default now()
);
create table if not exists public.weather_records (
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete set null, location text not null,
  data jsonb not null, created_at timestamptz not null default now()
);
create table if not exists public.risk_assessments (
  id bigint generated by default as identity primary key,
  crop_scan_id bigint not null references public.crop_scans(id) on delete cascade,
  score smallint not null check (score between 0 and 100), level text not null check (level in ('LOW','MEDIUM','HIGH')),
  reasons jsonb not null default '[]', created_at timestamptz not null default now()
);
create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  crop_id bigint references public.crops(id) on delete set null, scan_id bigint references public.crop_scans(id) on delete set null,
  alert_type text not null default 'risk', severity text not null default 'HIGH', title text not null default 'Crop health alert',
  message text not null, is_read smallint not null default 0 check(is_read in (0,1)), dedupe_key text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(), unique(user_id,dedupe_key)
);
create table if not exists public.expert_reviews (
  id bigint generated by default as identity primary key,
  scan_id bigint not null references public.crop_scans(id) on delete cascade,
  farmer_id bigint references public.users(id) on delete set null, expert_id bigint references public.users(id) on delete set null,
  status text not null default 'pending' check (status in ('pending','assigned','reviewed','closed')),
  request_note text, response text, confirmed_finding text, confirmed_type text check (confirmed_type is null or confirmed_type in ('disease','pest')),
  severity text, recommendation text, created_at timestamptz not null default now(), reviewed_at timestamptz, updated_at timestamptz not null default now()
);
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key, actor_id bigint references public.users(id) on delete set null,
  action text not null, entity_type text not null, entity_id text, details jsonb not null default '{}', created_at timestamptz not null default now()
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key, user_id bigint not null references public.users(id) on delete cascade,
  channel text not null default 'in_app' check (channel in ('in_app','email','sms','whatsapp')),
  status text not null default 'pending', title text not null, message text not null,
  created_at timestamptz not null default now(), sent_at timestamptz
);

